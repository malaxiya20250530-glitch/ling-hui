# ── 模拟对话引擎 ──────────────────────────────────────

def mock_chat(user_input: str) -> str:
    """基于关键词匹配的本地对话引擎，返回回复文本"""
    user_input = user_input.strip()
    if not user_input:
        return "主人？你在吗……？"

    # 按优先级匹配关键词模式
    for pattern, templates in REPLIES.items():
        match = re.search(pattern, user_input, re.IGNORECASE)
        if match:
            reply = random.choice(templates)
            # 替换捕获组 $1, $2...
            for i, group in enumerate(match.groups(), 1):
                reply = reply.replace(f"${i}", group)
            return reply

    return random.choice(DEFAULT_REPLIES)


